#!/usr/bin/env node
/**
 * Assembles the single-file app (public/index.html) from src/.
 *
 *   src/index.html        page shell (markup) with <!--@include {...}--> markers
 *   src/styles/*.css      stylesheets, inlined where their marker sits
 *   src/legacy/*.js       feature modules, inlined in order; started by the core
 *   src/core/**\/*.ts      typed core (storage, sync, boot), bundled with esbuild
 *   src/about/about.html  the About page, embedded as base64
 *
 * Output is deterministic: the same src/ always produces the same bytes, and CI
 * fails if the committed public/index.html is stale (npm run build:check).
 *
 *   node scripts/build.mjs            write public/index.html
 *   node scripts/build.mjs --check    exit 1 if public/index.html is out of date
 *   node scripts/build.mjs --out FILE write somewhere else
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const args = process.argv.slice(2);
const check = args.includes('--check');
const outArg = args.indexOf('--out');
const OUT = outArg >= 0 ? resolve(args[outArg + 1]) : join(ROOT, 'public', 'index.html');
const BANNER = '<!-- Built from src/ by scripts/build.mjs. Do not edit this file by hand: change src/ and run `npm run build`. -->\n';

function read(rel) {
  return readFileSync(join(SRC, rel), 'utf8').replace(/\r\n/g, '\n');
}

async function bundleCore() {
  const entry = join(SRC, 'core', 'main.ts');
  if (!existsSync(entry)) return '';
  const esbuild = await import('esbuild');
  const r = await esbuild.build({
    entryPoints: [entry], bundle: true, write: false, format: 'iife', target: ['es2020'],
    platform: 'browser', legalComments: 'none', charset: 'utf8', minify: false, sourcemap: false,
    logLevel: 'silent',
    define: { __DAILY_VERSION__: JSON.stringify(JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version) },
  });
  return r.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
}

function guard(text, what) {
  if (/<\/script/i.test(text) && what !== 'style') throw new Error(`${what} contains a closing </script> tag`);
  if (/<\/style/i.test(text) && what === 'style') throw new Error('stylesheet contains a closing </style> tag');
  return text;
}

async function build() {
  const hasCore = existsSync(join(SRC, 'core', 'main.ts'));
  let html = read('index.html');
  const about = Buffer.from(read('about/about.html'), 'utf8').toString('base64');
  html = html.replace(/<!--@include (\{.*?\})-->/g, (_, json) => {
    const spec = JSON.parse(json);
    const body = read(spec.file).replace(/\n$/, '');
    const id = spec.id ? ` id="${spec.id}"` : '';
    if (spec.tag === 'style') return `<style${id}>\n${guard(body, 'style')}\n</style>`;
    const code = body.replace('"__ABOUT_DOC_B64__"', JSON.stringify(about));
    // With the core present, feature modules ship inert and the core starts them once storage
    // has loaded; without it they run as ordinary scripts.
    const type = hasCore ? ' type="text/x-daily-module"' : '';
    return `<script${type}${id || ` id="m-${spec.file.replace(/\W+/g, '-')}"`}>\n${guard(code, 'script')}\n</script>`;
  });
  const core = await bundleCore();
  html = html.replace(/<!--@core-->\n?/, core ? `<script id="daily-core">\n${core}</script>\n` : '');
  if (/<!--@/.test(html)) throw new Error('Unresolved build marker in src/index.html');
  return html.replace(/^<!DOCTYPE html>\n/i, m => m + BANNER);
}

const html = await build();
if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== html) {
    console.error('public/index.html is out of date. Run `npm run build` and commit the result.');
    process.exit(1);
  }
  console.log('public/index.html is up to date.');
} else {
  writeFileSync(OUT, html);
  console.log(`Built ${OUT.replace(ROOT + '/', '')} (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB).`);
}
